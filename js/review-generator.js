  // ---------- helpers ----------
  function pick(a) { return a[Math.floor(Math.random() * a.length)]; }

  function shuffle(a) {
    a = a.slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1)), t = a[i];
      a[i] = a[j];
      a[j] = t;
    }
    return a;
  }

  function hashText(s) {
    var h = 2166136261;
    for (var i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return (h >>> 0).toString(36);
  }

  // ---------- local (same browser) no-repeat ----------
  function loadUsed() {
    try {
      var raw = localStorage.getItem(USED_KEY);
      used = raw ? JSON.parse(raw) : [];
      if (!Array.isArray(used)) used = [];
    } catch (e) {
      used = [];
    }
    usedSet = {};
    used.forEach(function (h) { usedSet[h] = true; });
  }

  function markUsed(h) {
    if (used.length >= USED_LIMIT) {   
      used = [];
      usedSet = {};
    }
    used.push(h);
    usedSet[h] = true;
    try { localStorage.setItem(USED_KEY, JSON.stringify(used)); } catch (e) {}
  }

  // ---------- global (all customers) no-repeat via Supabase ----------
 
  function claimGlobal(h) {
    if (!SUPABASE_URL || SUPABASE_URL.indexOf('YAHAN_') !== -1) {
      return Promise.resolve(true);    
    }
    return fetch(SUPABASE_URL + '/rest/v1/used_reviews', {
      method: 'POST',
      headers: {
        'apikey': SUPABASE_KEY,
        'Content-Type': 'application/json',
        'Prefer': 'return=minimal'
      },
      body: JSON.stringify({ id: CYCLE + '_' + h })
    }).then(function (res) {
      if (res.status === 409) return false;   
      return true;                           
    }).catch(function () {
      return true;                            
    });
  }

  // ---------- review builder (always 500 characters or less) ----------
  function build(svc) {
    var open = pick(OPENERS);
    var service = pick(SERVICE_LINES[svc]);
    var close = pick(CLOSERS);

    var middle = shuffle([
      { k: 'team', t: pick(TEAM) },
      { k: 'place', t: pick(PLACE) },
      { k: 'value', t: pick(VALUE) }
    ]);

    function compose() {
      return [open, service]
        .concat(middle.map(function (m) { return m.t; }))
        .concat([close])
        .join(' ');
    }

    var text = compose();

    // too long? drop value, then place, then team (in that order)
    var dropOrder = ['value', 'place', 'team'];
    for (var i = 0; i < dropOrder.length && text.length > MAX_LEN; i++) {
      var key = dropOrder[i];
      middle = middle.filter(function (m) { return m.k !== key; });
      text = compose();
    }
    return text;
  }

  function showReview(text) {
    $('rg-text').value = text;
    $('rg-result').style.display = 'block';
    $('rg-msg').textContent = '';
    $('st2').classList.add('active');
    $('st3').classList.add('active');
  }

  function generate() {
    var svc = $('rg-service').value;
    var b1 = $('rg-generate'), b2 = $('rg-shuffle');
    var tries = 0;
    b1.disabled = b2.disabled = true;

    function done() { b1.disabled = b2.disabled = false; }

    function attempt() {
      tries++;
      var text = build(svc);
      var h = hashText(text);
      if ((text === last || usedSet[h]) && tries < 200) return attempt();
      return claimGlobal(h).then(function (ok) {
        if (!ok && tries < 200) return attempt();
        last = text;
        markUsed(h);
        showReview(text);
      });
    }

    attempt().then(done, done);
  }

  function copyText(text) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(text);
    }
    return new Promise(function (resolve, reject) {
      var ta = $('rg-text');
      ta.select();
      try { document.execCommand('copy') ? resolve() : reject(); } catch (e) { reject(e); }
    });
  }

